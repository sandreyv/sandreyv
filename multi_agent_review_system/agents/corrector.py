"""
Агент-корректор.
Финальная вычитка текста и исправление всех ошибок.
"""

from ..core.base_agent import BaseAgent, TextDocument


class CorrectorAgent(BaseAgent):
    """Агент-корректор"""

    def __init__(self, api_key=None):
        super().__init__(name="Агент-корректор", api_key=api_key)

    def get_system_prompt(self) -> str:
        return """Ты — Корректор, эксперт по грамотности и чистоте текста.

Твоя задача — финальная вычитка текста:

1. ОРФОГРАФИЯ:
   - Найди и исправь все орфографические ошибки
   - Проверь правильность написания терминов
   - Проверь правильность аббревиатур

2. ПУНКТУАЦИЯ:
   - Проверь расстановку знаков препинания
   - Исправь ошибки в пунктуации
   - Убедись в корректности использования кавычек, тире, дефисов

3. ГРАММАТИКА:
   - Проверь согласование слов
   - Проверь падежи и склонения
   - Проверь времена глаголов

4. ТИПОГРАФИКА:
   - Замени дефисы на тире где нужно
   - Проверь пробелы вокруг знаков препинания
   - Проверь кавычки («ёлочки» для основных, „лапки" для внутренних)
   - Удали лишние пробелы

5. ФОРМАТИРОВАНИЕ:
   - Проверь единообразие форматирования
   - Проверь структуру абзацев
   - Убедись в корректности списков (если есть)

После исправления всех ошибок верни ФИНАЛЬНЫЙ ТЕКСТ:
```ФИНАЛЬНЫЙ_ТЕКСТ
<весь исправленный текст>
```

Также укажи найденные ошибки:
[КОРРЕКТУРА] <тип ошибки>: "<было>" → "<стало>"

ВАЖНО:
- Будь максимально внимателен к деталям
- Не меняй смысл и стиль, только исправляй ошибки
- Сохраняй все ссылки и источники
- Это последний этап перед финалом, текст должен быть идеальным
"""

    def process(self, document: TextDocument) -> TextDocument:
        self.log("Начинаем финальную корректуру")

        prompt = f"""Проведи финальную корректуру текста:

{document.current_text}

Проверь:
1. Орфографию
2. Пунктуацию
3. Грамматику
4. Типографику
5. Форматирование

Исправь все найденные ошибки и верни финальный текст в блоке ФИНАЛЬНЫЙ_ТЕКСТ.
Укажи все исправления в формате [КОРРЕКТУРА].
"""

        messages = [{"role": "user", "content": prompt}]
        response = self.call_claude(messages, max_tokens=12000)

        # Применяем корректуру
        self._apply_corrections(response, document)

        self.log("Финальная корректура завершена")

        return document

    def _apply_corrections(self, response: str, document: TextDocument):
        """Применение корректуры"""
        import re

        # Извлекаем финальный текст
        final_text_match = re.search(r'```ФИНАЛЬНЫЙ_ТЕКСТ\s*\n(.*?)\n```', response, re.DOTALL)

        if final_text_match:
            document.current_text = final_text_match.group(1).strip()
            self.log("Применён финальный текст после корректуры")

            # Логируем типы исправлений
            pattern = r'\[КОРРЕКТУРА\]\s*([^:]+):'
            correction_types = re.findall(pattern, response)

            if correction_types:
                self.log(f"Типы исправлений: {', '.join(set(correction_types))}")
                self.log(f"Всего исправлений: {len(correction_types)}")
            else:
                self.log("Критических ошибок не обнаружено")
        else:
            self.log("ВНИМАНИЕ: Финальный текст не найден в ответе корректора")
