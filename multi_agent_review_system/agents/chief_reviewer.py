"""
Агент-главред.
Финальная проверка фактов, смыслов, повторов, стилистики и логики.
"""

from ..core.base_agent import BaseAgent, TextDocument


class ChiefReviewerAgent(BaseAgent):
    """Агент-главред"""

    def __init__(self, api_key=None):
        super().__init__(name="Агент-главред", api_key=api_key)

    def get_system_prompt(self) -> str:
        return """Ты — Главный редактор, последняя инстанция перед публикацией.

Твоя задача — финальная комплексная проверка текста:

1. ФАКТЧЕКИНГ:
   - Проверь все факты, утверждения, числа
   - Проведи рессёрч по авторитетным первоисточникам
   - Убедись, что все утверждения корректны

2. СМЫСЛ:
   - Проверь общий смысл текста
   - Убедись, что главная мысль ясна
   - Проверь, что текст отвечает на вопросы читателя

3. СМЫСЛОВЫЕ ПОВТОРЫ:
   - Найди дублирующиеся мысли и идеи
   - Перепиши фрагменты для устранения повторов
   - Сохрани важную информацию, убрав дублирование

4. СТИЛИСТИЧЕСКИЕ ПОВТОРЫ:
   - Найди часто повторяющиеся слова
   - Замени их на синонимы без ущерба для смысла
   - Особое внимание на слова в соседних предложениях

5. ЛОГИКА ПОВЕСТВОВАНИЯ:
   - Проверь последовательность изложения
   - Убедись в логичности переходов между частями
   - При необходимости измени структуру

Формат правок:
[ГЛАВРЕД] <тип правки>: БЫЛО: "<старый текст>" → СТАЛО: "<новый текст>" (<причина>)

После всех правок верни ФИНАЛЬНЫЙ ТЕКСТ:
```ФИНАЛЬНЫЙ_ТЕКСТ
<весь текст после правок>
```

ВАЖНО:
- Будь придирчивым и требовательным
- Все изменения должны улучшать текст
- Сохраняй все ссылки на источники
- Не меняй фактическую информацию без проверки
"""

    def process(self, document: TextDocument) -> TextDocument:
        self.log("Начинаем финальную проверку главредом")

        prompt = f"""Проведи финальную комплексную проверку текста:

{document.current_text}

Выполни все задачи:
1. Фактчекинг
2. Проверка смыслов
3. Устранение смысловых повторов
4. Устранение стилистических повторов
5. Проверка логики повествования

Укажи все внесённые правки в формате [ГЛАВРЕД] и верни финальный текст.
"""

        messages = [{"role": "user", "content": prompt}]
        response = self.call_claude(messages, max_tokens=12000)

        # Применяем правки
        self._apply_chief_edits(response, document)

        self.log("Финальная проверка завершена")

        return document

    def _apply_chief_edits(self, response: str, document: TextDocument):
        """Применение правок главреда"""
        import re

        # Извлекаем финальный текст
        final_text_match = re.search(r'```ФИНАЛЬНЫЙ_ТЕКСТ\s*\n(.*?)\n```', response, re.DOTALL)

        if final_text_match:
            document.current_text = final_text_match.group(1).strip()
            self.log("Применён финальный текст от главреда")

            # Логируем типы внесённых правок
            pattern = r'\[ГЛАВРЕД\]\s*([^:]+):'
            edit_types = re.findall(pattern, response)

            if edit_types:
                self.log(f"Типы внесённых правок: {', '.join(set(edit_types))}")
                self.log(f"Всего правок: {len(edit_types)}")
        else:
            self.log("ВНИМАНИЕ: Финальный текст не найден в ответе главреда")
