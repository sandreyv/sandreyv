"""
Мета-агент — анализатор задачи и генератор финального отчёта.
Используется в начале (анализ задачи) и в конце (сбор отчёта).
"""

from ..core.base_agent import BaseAgent, TextDocument


class MetaAgent(BaseAgent):
    """
    Мета-агент координирует процесс и генерирует финальный отчёт.

    Роль:
    - В начале: анализирует задачу и подготавливает документ
    - В конце: собирает финальный отчёт о проделанной работе
    """

    def __init__(self, api_key=None):
        super().__init__(name="Мета-агент", api_key=api_key)
        self.mode = "report"  # "analysis" или "report"

    def get_system_prompt(self) -> str:
        if self.mode == "analysis":
            return """Ты — Мета-агент, координатор процесса анализа текста.

Твоя задача:
1. Проанализировать полученный текст
2. Определить его тематику, стиль, целевую аудиторию
3. Выявить основные аспекты, которые требуют внимания
4. Подготовить краткую аналитическую справку для остальных агентов

Будь точным и конкретным в своих наблюдениях."""

        else:  # report mode
            return """Ты — Мета-агент, генератор финального отчёта.

Твоя задача:
1. Изучить всю проделанную работу агентов
2. Составить подробный отчёт о каждом этапе обработки
3. Выделить ключевые изменения и улучшения
4. Предоставить финальный текст, готовый к использованию

Отчёт должен быть структурированным и информативным."""

    def analyze_task(self, text: str) -> TextDocument:
        """Анализ задачи и создание документа"""
        self.mode = "analysis"
        self.log("Начинаем анализ задачи")

        document = TextDocument(
            original_text=text,
            current_text=text,
            metadata={}
        )

        # Создаём промпт для анализа
        prompt = f"""Проанализируй следующий текст и предоставь краткую аналитическую справку:

{text}

Опиши:
1. Тематику и направление
2. Стиль изложения
3. Целевую аудиторию
4. Основные аспекты, требующие внимания (фактура, стиль, логика, фактчекинг)
"""

        messages = [{"role": "user", "content": prompt}]
        analysis = self.call_claude(messages, max_tokens=2000)

        # Сохраняем анализ в метаданные
        document.metadata['initial_analysis'] = analysis
        document.processing_history.append(f"Мета-агент: Выполнен начальный анализ")

        self.log("Анализ задачи завершён")

        return document

    def process(self, document: TextDocument) -> TextDocument:
        """
        Обработка документа мета-агентом.
        Этот метод вызывается в конце цепочки для генерации финального отчёта.
        """
        self.mode = "report"
        self.log("Генерируем финальный отчёт")

        # Мета-агент не меняет текст, только добавляет метаинформацию
        prompt = f"""Изучи результаты работы всех агентов и составь краткое резюме о проделанной работе.

{self.prepare_document_for_prompt(document)}

Составь краткое резюме (3-5 пунктов) о ключевых улучшениях, которые были внесены в текст."""

        messages = [{"role": "user", "content": prompt}]
        summary = self.call_claude(messages, max_tokens=1500)

        document.metadata['final_summary'] = summary
        self.log("Финальный отчёт сгенерирован")

        return document
